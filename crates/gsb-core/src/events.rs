//! Events: what the system pushes to us (`docs/EVENTS.md`, round e2 —
//! core routing). The twin of [`crate::calls`]: there a player asks and
//! the server answers; here server code (a service, an admin task, a
//! room) tells an identity, a room or everyone something nobody asked
//! for.
//!
//! ```text
//! Publisher ──try_send──▶ registry (the router: identity → place)
//!                          │ per recipient, per leg: a sequence number
//!          CLIENT leg      │                    WORLD leg
//!   ConnIn::Push → the connection actor   the room's / shard's OWN
//!   → a PUSH frame on its outbound        event mailbox → EVENTS phase
//!   (no room on the way)                  → the `Events` table → systems
//! ```
//!
//! - The destination is the event TYPE's (`.proto` `(gsb.event)`,
//!   generated by `gsb-build`): [`WorldEvent`] a room may take,
//!   [`ClientEvent`] a client may listen for; taking a client-only event
//!   in a room does not compile.
//! - [`Publisher`] — the only right to push. Every push is ONE `try_send`
//!   into the registry's mailbox; the body is encoded once
//!   (`push_many` to 10 000 identities is one encode and one message).
//!   A refusal at the handle is typed ([`PushRefused`]); every later loss
//!   is counted by name where it happens (`crate::metrics::RouterCounts`,
//!   `PushCounts`, `EventCounts`) — delivery is at most once, and the
//!   per-(publisher, identity, leg) sequence number lets a client see a
//!   gap.
//! - [`Events`] — the room-side table, lent to the game each tick
//!   ([`GameLogic::update_with_events`](crate::room::GameLogic::update_with_events)).
//!   The EVENTS phase (CONTROL → RESPONSES → **EVENTS** → READ) fills
//!   it; systems `take::<E>()`; what nobody took is dropped at tick end
//!   and counted (`events_untaken`), never carried over.
//!
//! The routing table itself ([`EventRoutes`](self) — crate-internal)
//! runs inside the registry actor, which already learns every fact it
//! reads (auth, join, leave, park, close); it is a struct of its own that
//! reads those facts through a narrow trait, so moving it to a dedicated
//! router actor later (EVENTS §12, "measure, then split") changes no
//! routing code.
//!
//! A shard migration keeps every (publisher, identity, leg) order: the
//! source keeps a tombstone and hands stragglers on over the shard FIFO,
//! the router seals the source once it learns the move (`Relocated`),
//! and the target holds the router's direct legs until the source's
//! fence (round e3, `docs/EVENTS.md` §7.3; [`TOMB_TTL`], [`FENCE_TTL`],
//! [`HOLD_CAP`]). Engine events (presence) are round e4; the input log,
//! replay and the ECS bindings e5; the client e6.

