//! The live service host on tower (SERVICES.md §4.1, Faz 2 — round q2).
//!
//! A `#[gsb_core::service]` trait's implementation is registered as
//! `Inventory::serve(PgInventory::new(db))` ([`Served`]) with a setup
//! closure over its tower stack ([`Setup`]):
//!
//! ```ignore
//! parts.service(Inventory::serve(PgInventory::new(db)), |s| {
//!     s.timeout(Duration::from_secs(3)).concurrency_limit(32).load_shed()
//! });
//! let inv: InventoryClient = parts.client();   // rooms (non-blocking)
//! let inv_h: InventoryHandle = parts.client(); // services, admin (awaitable)
//! ```
//!
//! Each service is a mailbox actor ([`spawn`]): its loop's one await is
//! the mailbox `recv`; every call is its own task whose one await is the
//! call through the stack (`oneshot`). No select, no lock. A layer's
//! error is mapped onto the call's typed ending — a timeout (the game's
//! `.timeout(d)`, or the host's default deadline
//! [`DEFAULT_SERVICE_TIMEOUT`]) → `CallError::TimedOut`, a shed →
//! `CallError::Refused(Refusal::Shed)`, any other → `Abandoned` — and
//! counted at the service ([`ServiceStats`]). Every call runs in a
//! `gsb.call` span (`service`, `method`, `trace`) and its latency lands
//! in its method's [`MethodStats`].
//!
//! The stop is F5's ([`Service`]): the stop message queues behind the
//! calls already in the mailbox; those are served, the mailbox closes
//! (a later call is `Refused(Gone)`), and the task ends once every call
//! it started has answered.

use std::any::{Any, TypeId};
use std::collections::HashMap;
use std::marker::PhantomData;
use std::pin::Pin;
use std::sync::Arc;
use std::sync::atomic::Ordering;
use std::time::{Duration, Instant};

use tower::ServiceBuilder;
use tower::ServiceExt;
use tower::layer::util::{Identity as Id, Stack};
use tracing::Instrument;

use crate::calls::contract::{CallCx, Refusal};
use crate::calls::route::{AnyOutcome, Mail, Reply, Route, ServiceStats};
use crate::service::{Service, hold};

/// A boxed layer error (what the host maps onto a call's ending).
pub type BoxError = Box<dyn std::error::Error + Send + Sync>;

/// The future a generated router returns.
pub type BoxFuture =
    Pin<Box<dyn std::future::Future<Output = Result<AnyOutcome, BoxError>> + Send + 'static>>;

/// The host's default per-call deadline (SERVICES.md §19 S6): a call
/// still running this long is ended `TimedOut`. The game's own
/// [`Setup::timeout`] replaces it; [`Setup::no_timeout`] removes it.
pub const DEFAULT_SERVICE_TIMEOUT: Duration = Duration::from_secs(30);

/// The default mailbox capacity of a hosted service.
pub const DEFAULT_MAILBOX: usize = 1024;

/// What the tower stack sees: the call's context and its bare message.
pub struct Dispatch<M> {
    /// The key, the caller, the verified player, the trace.
    pub cx: CallCx,
    /// The service's bare message (the call without its answer right).
    pub msg: M,
}

/// A service's identity (generated by `#[service]` on its `Kind`): its
/// name, its methods, its two messages.
pub trait ServiceKind: 'static {
    /// The service's name (the trait's).
    const NAME: &'static str;
    /// Its methods, in declaration order.
    const METHODS: &'static [&'static str];
    /// The mailbox message (its variants carry the calls' `Ask`s).
    type Msg: Send + 'static;
    /// The bare message the tower stack sees.
    type Bare: Send + 'static;
    /// Take the answer right out of a mailbox message.
    fn split(msg: Self::Msg) -> (Self::Bare, Reply);
    /// The index of a bare message's method in [`Self::METHODS`].
    fn method(bare: &Self::Bare) -> usize;
    /// Cover in a log FILE (feature `record`) the outcomes of every
    /// method whose `Response` and `Error` both have a wire form
    /// ([`WireMessage`](crate::calls::WireMessage)); a method's outcome
    /// without one is written missing (counted). `#[service]` generates
    /// it (B173); a hand-written kind covers nothing. Called through
    /// [`Calls::record_service`](crate::calls::Calls::record_service).
    fn record_codecs(_calls: &mut crate::calls::Calls) {}
}

/// "`S` implements this service": how to build its tower router
/// (generated for every implementation of the trait).
pub trait ServiceDef<S>: ServiceKind {
    /// The generated router.
    type Router: tower::Service<
            Dispatch<Self::Bare>,
            Response = AnyOutcome,
            Error = BoxError,
            Future = BoxFuture,
        > + Clone
        + Send
        + 'static;
    /// The router over `svc`.
    fn router(svc: Arc<S>) -> Self::Router;
}

/// An implementation ready for a host (`Inventory::serve(PgInventory::new(db))`).
pub struct Served<K, S> {
    svc: S,
    _k: PhantomData<fn() -> K>,
}

impl<K, S> Served<K, S> {
    /// Wrap an implementation (what the generated `serve` does).
    pub fn new(svc: S) -> Self {
        Self {
            svc,
            _k: PhantomData,
        }
    }

    /// The implementation (TEST mode's host runs it without tower:
    /// `determinism::Sim::served`).
    pub(crate) fn into_inner(self) -> S {
        self.svc
    }
}

/// A generated client (`…Client` or `…Handle`): built from the service's
/// route.
pub trait ServiceClient: Sized {
    /// The service it calls.
    type Kind: ServiceKind;
    /// The client over `route`.
    fn from_route(route: Route<<Self::Kind as ServiceKind>::Msg>) -> Self;
}

/// What a registration's setup closure (`|s| ..`) works on: the tower
/// stack, the mailbox size, the default deadline.
pub struct Setup<L> {
    builder: ServiceBuilder<L>,
    mailbox: usize,
    deadline: Option<Duration>,
}

impl Setup<Id> {
    /// The defaults: no layer, a [`DEFAULT_MAILBOX`] mailbox, the
    /// [`DEFAULT_SERVICE_TIMEOUT`] deadline.
    pub fn new() -> Self {
        Self {
            builder: ServiceBuilder::new(),
            mailbox: DEFAULT_MAILBOX,
            deadline: Some(DEFAULT_SERVICE_TIMEOUT),
        }
    }
}

impl Default for Setup<Id> {
    fn default() -> Self {
        Self::new()
    }
}

impl<L> Setup<L> {
    fn map<T>(
        self,
        f: impl FnOnce(ServiceBuilder<L>) -> ServiceBuilder<T>,
        deadline: impl FnOnce(Option<Duration>) -> Option<Duration>,
    ) -> Setup<T> {
        Setup {
            builder: f(self.builder),
            mailbox: self.mailbox,
            deadline: deadline(self.deadline),
        }
    }

    /// tower's timeout layer: a call running longer than `d` ends
    /// `TimedOut`. Replaces the host's default deadline.
    pub fn timeout(self, d: Duration) -> Setup<Stack<tower::timeout::TimeoutLayer, L>> {
        self.map(|b| b.timeout(d), |_| None)
    }

    /// tower's concurrency limit: at most `n` calls run at once (the
    /// rest wait for a slot — or are shed, under [`Self::load_shed`]).
    pub fn concurrency_limit(
        self,
        n: usize,
    ) -> Setup<Stack<tower::limit::ConcurrencyLimitLayer, L>> {
        self.map(|b| b.concurrency_limit(n), |d| d)
    }

    /// tower's load shedding: a call the inner stack is not ready for
    /// ends `Refused(Shed)` at once.
    pub fn load_shed(self) -> Setup<Stack<tower::load_shed::LoadShedLayer, L>> {
        self.map(|b| b.load_shed(), |d| d)
    }

    /// Any other tower layer (the game's own: tracing, metrics, retry …).
    /// Its errors end a call `Abandoned` (counted `calls_failed`).
    pub fn layer<T>(self, layer: T) -> Setup<Stack<T, L>> {
        self.map(|b| b.layer(layer), |d| d)
    }

    /// The mailbox capacity (default [`DEFAULT_MAILBOX`]; at least 1).
    /// Size it ≥ rooms × their share (SERVICES.md §5.3).
    pub fn mailbox(mut self, n: usize) -> Self {
        self.mailbox = n.max(1);
        self
    }

    /// No deadline at all (neither the default nor a `.timeout`): the
    /// calling table's own deadline (`RoomConfig::call_timeout`) is then
    /// the only one.
    pub fn no_timeout(mut self) -> Self {
        self.deadline = None;
        self
    }
}

/// Counts a call that ended without its answer being produced (its task
/// unwound: a panic in the service).
struct Unanswered {
    stats: Arc<ServiceStats>,
    done: bool,
}

impl Drop for Unanswered {
    fn drop(&mut self) {
        if !self.done {
            self.stats.calls_abandoned.fetch_add(1, Ordering::Relaxed);
        }
    }
}

/// Spawn a service on the current tokio runtime: its route (for clients)
/// and its [`Service`] (the F5 stop). See the module docs.
pub fn spawn<K, S, L, F>(served: Served<K, S>, setup: F) -> (Route<K::Msg>, Service)
where
    K: ServiceDef<S>,
    S: Send + Sync + 'static,
    F: FnOnce(Setup<Id>) -> Setup<L>,
    L: tower::Layer<K::Router>,
    L::Service: tower::Service<Dispatch<K::Bare>, Response = AnyOutcome> + Clone + Send + 'static,
    <L::Service as tower::Service<Dispatch<K::Bare>>>::Future: Send,
    <L::Service as tower::Service<Dispatch<K::Bare>>>::Error: Into<BoxError> + Send,
{
    let setup = setup(Setup::new());
    let deadline = setup.deadline;
    let stack = setup.builder.service(K::router(Arc::new(served.svc)));
    let (route, mut rx) = Route::with_methods(K::NAME, setup.mailbox, K::METHODS);
    let stats = Arc::clone(&route.stats);
    let task = tokio::spawn(async move {
        let (work, in_flight) = hold();
        while let Some(mail) = rx.recv().await {
            let env = match mail {
                Mail::Call(env) => env,
                Mail::Stop => break,
            };
            stats.calls_received.fetch_add(1, Ordering::Relaxed);
            let (bare, reply) = K::split(env.msg);
            let method = K::method(&bare);
            let span = tracing::debug_span!(
                "gsb.call",
                service = K::NAME,
                method = K::METHODS.get(method).copied().unwrap_or("?"),
                trace = env.cx.trace_id(),
            );
            let svc = stack.clone();
            let stats = Arc::clone(&stats);
            let work = work.clone();
            let cx = env.cx;
            tokio::spawn(
                async move {
                    let mut guard = Unanswered {
                        stats: Arc::clone(&stats),
                        done: false,
                    };
                    let start = Instant::now();
                    let call = svc.oneshot(Dispatch { cx, msg: bare });
                    let result: Result<AnyOutcome, BoxError> = match deadline {
                        Some(d) => match tokio::time::timeout(d, call).await {
                            Ok(r) => r.map_err(Into::into),
                            Err(elapsed) => Err(Box::new(elapsed)),
                        },
                        None => call.await.map_err(Into::into),
                    };
                    guard.done = true;
                    end(result, reply, &stats);
                    let us = u64::try_from(start.elapsed().as_micros()).unwrap_or(u64::MAX);
                    if let Some(m) = stats.methods.get(method) {
                        m.record(us);
                    }
                    tracing::debug!(latency_us = us, "service call done");
                    drop(work);
                }
                .instrument(span),
            );
        }
        // Refuse what comes after the stop, then let what was started
        // answer.
        drop(rx);
        drop(work);
        in_flight.wait().await;
    });
    let stopper = route.clone();
    (route, Service::new(K::NAME, task, move || stopper.stop()))
}

/// Map a call's result through the stack onto its ending (and count the
/// engine-side ones).
fn end(result: Result<AnyOutcome, BoxError>, reply: Reply, stats: &ServiceStats) {
    match result {
        Ok(out) => reply.complete(out),
        Err(e) => {
            if e.is::<tower::timeout::error::Elapsed>() || e.is::<tokio::time::error::Elapsed>() {
                stats.calls_timed_out.fetch_add(1, Ordering::Relaxed);
                reply.timed_out();
            } else if e.is::<tower::load_shed::error::Overloaded>() {
                stats.calls_shed.fetch_add(1, Ordering::Relaxed);
                reply.refuse(Refusal::Shed);
            } else {
                stats.calls_failed.fetch_add(1, Ordering::Relaxed);
                tracing::debug!(error = %e, "a service layer failed a call");
                reply.abandon();
            }
        }
    }
}

/// A composition-root mistake in registering services (BACKLOG B169).
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum RegisterError {
    /// A service of this kind is already registered: one kind, one route
    /// (two implementations of one trait need two traits today).
    #[error("service {service} is registered twice")]
    Duplicate {
        /// The service's name (its trait's).
        service: &'static str,
    },
}

/// The live services of a composition root: registered once, each
/// handed out as clients by its kind, stopped together after the rooms
/// (F5: [`Self::into_stops`]).
#[derive(Default)]
pub struct Services {
    routes: HashMap<TypeId, Box<dyn Any + Send + Sync>>,
    stats: Vec<(&'static str, Arc<ServiceStats>)>,
    stops: Vec<Service>,
}

impl std::fmt::Debug for Services {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Services")
            .field(
                "services",
                &self.stats.iter().map(|(n, _)| *n).collect::<Vec<_>>(),
            )
            .finish()
    }
}

impl Services {
    /// No services.
    pub fn new() -> Self {
        Self::default()
    }

    /// Register and spawn a service:
    /// `services.service(Inventory::serve(PgInventory::new(db)), |s| s.timeout(..))?`.
    ///
    /// # Errors
    ///
    /// [`RegisterError::Duplicate`] when a service of the same kind is
    /// already registered (a composition-root mistake: one kind, one
    /// route). Nothing is spawned then; the first registration stays.
    pub fn service<K, S, L, F>(
        &mut self,
        served: Served<K, S>,
        setup: F,
    ) -> Result<&mut Self, RegisterError>
    where
        K: ServiceDef<S>,
        S: Send + Sync + 'static,
        F: FnOnce(Setup<Id>) -> Setup<L>,
        L: tower::Layer<K::Router>,
        L::Service:
            tower::Service<Dispatch<K::Bare>, Response = AnyOutcome> + Clone + Send + 'static,
        <L::Service as tower::Service<Dispatch<K::Bare>>>::Future: Send,
        <L::Service as tower::Service<Dispatch<K::Bare>>>::Error: Into<BoxError> + Send,
    {
        if self.routes.contains_key(&TypeId::of::<K>()) {
            return Err(RegisterError::Duplicate { service: K::NAME });
        }
        let (route, stop) = spawn(served, setup);
        self.stats.push((K::NAME, Arc::clone(route.stats())));
        self.routes.insert(TypeId::of::<K>(), Box::new(route));
        self.stops.push(stop);
        Ok(self)
    }

    /// A generated client of a registered service, `None` if it is not
    /// registered.
    pub fn try_client<C: ServiceClient>(&self) -> Option<C> {
        self.routes
            .get(&TypeId::of::<C::Kind>())
            .and_then(|r| r.downcast_ref::<Route<<C::Kind as ServiceKind>::Msg>>())
            .map(|r| C::from_route(r.clone()))
    }

    /// A generated client of a registered service (`InventoryClient` for
    /// rooms, `InventoryHandle` for services and admin).
    ///
    /// # Panics
    ///
    /// When the service is not registered.
    pub fn client<C: ServiceClient>(&self) -> C {
        self.try_client().unwrap_or_else(|| {
            panic!(
                "service {} is not registered",
                <C::Kind as ServiceKind>::NAME
            )
        })
    }

    /// Every registered service's name and counters, in registration order.
    pub fn stats(&self) -> &[(&'static str, Arc<ServiceStats>)] {
        &self.stats
    }

    /// The services' stops, in registration order (the clients already
    /// handed out keep working until each one stops).
    pub fn into_stops(self) -> Vec<Service> {
        self.stops
    }

    /// The stops of the services registered since the last call (the
    /// registry moves them into its own stop list as it goes, keeping
    /// one registration order with hand-written services).
    pub fn take_stops(&mut self) -> Vec<Service> {
        std::mem::take(&mut self.stops)
    }
}

